<#
.SYNOPSIS
  Assembles the YAYA 6 sample ghost (samples/yaya-ghost) into an SSP-ready folder.

.DESCRIPTION
  Copies the ghost sources, yaya.dll (+ its license files), the x86 SAORI
  bridge, the x64 3D runtime, Uka (CC BY 4.0) and generated motions into
  build\ghost\ukagaka3d_sample. Idle, walk, sit and grab are generated for the
  packaged model by uka3d_motiongen (original data, fitted to its legs). Optionally packs a .nar and/or swaps in a
  local model (which is never committed; the output folder is git-ignored).

  Prerequisites: scripts\build.ps1 -Test (x64 + x86 builds and test assets).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\package-ghost.ps1 -YayaDll C:\path\to\yaya.dll
  powershell -ExecutionPolicy Bypass -File scripts\package-ghost.ps1 -YayaDll ..\yaya\yaya.dll -Nar
  # Use your own (non-redistributable) model locally:
  powershell -ExecutionPolicy Bypass -File scripts\package-ghost.ps1 -YayaDll ..\yaya\yaya.dll `
      -ModelDir "C:\MMD\MyModel" -ModelFile "MyModel.pmx"
#>
param(
    [Parameter(Mandatory = $true)][string]$YayaDll,
    [ValidateSet('Debug', 'Release')][string]$Config = 'Release',
    [string]$Output = '',
    [string]$ModelDir = '',
    [string]$ModelFile = '',
    # Uka texture size: 2048 (default, about 1/3 of the memory of the originals), 1024 or 4096 (unchanged)
    [ValidateSet('4096', '2048', '1024')][string]$UkaTextureSize = '2048',
    [switch]$Nar
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
if (-not $Output) { $Output = Join-Path $root 'build\ghost\ukagaka3d_sample' }

$runtime = Join-Path $root "build\msvc-x64\$Config\ukagaka3d.exe"
$saori = Join-Path $root "build\msvc-x86\$Config\ukagaka3d_saori.dll"
$assets = Join-Path $root 'build\msvc-x64\test-assets'
$yaya = (Resolve-Path $YayaDll).Path
foreach ($f in @($runtime, $saori, $assets, $yaya)) {
    if (-not (Test-Path -LiteralPath $f)) { throw "Not found: $f (run scripts\build.ps1 -Test first)" }
}

if (Test-Path -LiteralPath $Output) { throw "Output already exists: $Output (choose a new -Output path)" }
if ($Nar) {
    foreach ($archive in @("$Output.nar", "$Output.zip")) {
        if (Test-Path -LiteralPath $archive) { throw "Output already exists: $archive (choose a new -Output path)" }
    }
}

if (-not $ModelDir) {
    # Pin the official model and textures without adding model binaries to Git.
    $ukaRevision = '659f0d1a740fec68bb2817dc9c694a35e7a15f12'
    $ukaHash = '4E9B7BB27272DB9ECA2FF7A8BF62834F62AFFAA2386DC5B55A8D49668B5AFF51'
    $cache = Join-Path $root 'build\cache'
    New-Item -ItemType Directory -Force $cache | Out-Null
    $ukaArchive = Join-Path $cache "uka-$ukaRevision.zip"
    if (-not (Test-Path -LiteralPath $ukaArchive)) {
        $download = Join-Path $cache "uka-$ukaRevision-$PID.download"
        try {
            $ProgressPreference = 'SilentlyContinue'
            Invoke-WebRequest -UseBasicParsing -Uri "https://codeload.github.com/mmdagent-ex/uka/zip/$ukaRevision" -OutFile $download
            if ((Get-FileHash -LiteralPath $download).Hash -ne $ukaHash) { throw 'Uka archive checksum mismatch' }
            Move-Item -LiteralPath $download -Destination $ukaArchive
        } finally {
            if (Test-Path -LiteralPath $download) { Remove-Item -LiteralPath $download }
        }
    }
    if ((Get-FileHash -LiteralPath $ukaArchive).Hash -ne $ukaHash) {
        throw "Uka cache checksum mismatch: $ukaArchive"
    }
}
New-Item -ItemType Directory -Force $Output | Out-Null
Copy-Item -Recurse (Join-Path $root 'samples\yaya-ghost\*') $Output

$master = Join-Path $Output 'ghost\master'
$d3 = Join-Path $master '3d'

# Only match the top-level sample model line, not accessory model properties.
$mainModelPattern = '(?m)^    "model":\s*"[^"\r\n]*"'
New-Item -ItemType Directory -Force (Join-Path $d3 'model'), (Join-Path $d3 'motion') | Out-Null

# YAYA 6 (BSD-3-Clause; AYA original license) - keep the license texts next to the DLL.
Copy-Item $yaya (Join-Path $master 'yaya.dll')
$yayaDir = Split-Path $yaya -Parent
foreach ($name in @('LICENSE', 'readme-original.txt', 'README.md')) {
    $src = Join-Path $yayaDir $name
    if (Test-Path $src) { Copy-Item $src (Join-Path $master "yaya_$name.txt".Replace('.txt.txt', '.txt').Replace('.md.txt', '.md')) }
}
if (-not (Test-Path (Join-Path $yayaDir 'LICENSE'))) { Write-Warning 'YAYA LICENSE not found next to yaya.dll; add it before redistributing.' }

Copy-Item $saori (Join-Path $master 'ukagaka3d_saori.dll')
Copy-Item $runtime (Join-Path $d3 'ukagaka3d.exe')
Copy-Item (Join-Path $root 'THIRD_PARTY_NOTICES.md') (Join-Path $d3 'THIRD_PARTY_NOTICES.md')
Copy-Item (Join-Path $root 'LICENSE') (Join-Path $d3 'LICENSE.txt')

# Motions generated by make_test_assets.
$accessories = Join-Path $d3 'accessories'
New-Item -ItemType Directory -Force $accessories | Out-Null
Copy-Item -LiteralPath (Join-Path $assets 'accessories\glasses.pmx') -Destination $accessories

$motions = @{
    '挨拶.vmd' = 'greet.vmd'; 'うなずき.vmd' = 'nod.vmd'; '待機テスト.vmd' = 'idle.vmd'
    '歩行.vmd' = 'walk.vmd'; '着席.vmd' = 'sit.vmd'; 'つまみ.vmd' = 'grab.vmd'
}
foreach ($kv in $motions.GetEnumerator()) {
    Copy-Item (Join-Path $assets "モーション\$($kv.Key)") (Join-Path $d3 "motion\$($kv.Value)")
}

# Optional local model (stays inside the ghost folder so the path policy allows it).
if ($ModelDir) {
    if (-not $ModelFile) { throw '-ModelFile is required with -ModelDir' }
    $dest = Join-Path $d3 'model\user'
    New-Item -ItemType Directory -Force $dest | Out-Null
    Copy-Item -Recurse (Join-Path $ModelDir '*') $dest
    if (-not (Test-Path (Join-Path $dest $ModelFile))) { throw "Model file not found: $ModelFile" }
    $jsonPath = Join-Path $master 'ukagaka3d.json'
    $json = [System.IO.File]::ReadAllText($jsonPath, [System.Text.Encoding]::UTF8)
    $modelRel = ('3d/model/user/' + $ModelFile.Replace('\', '/'))
    $json = [regex]::Replace($json, $mainModelPattern, ('    "model": "' + $modelRel + '"'))
    [System.IO.File]::WriteAllText($jsonPath, $json, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Local model: $modelRel (do not redistribute this folder)" -ForegroundColor Yellow
} else {
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $dest = Join-Path $d3 'model\uka'
    New-Item -ItemType Directory -Force (Join-Path $dest 'tex') | Out-Null
    # The textures MS_Uka.pmx references at this revision (tex/hair.png is not used).
    $ukaTextures = @('eye.png', 'face.png', 'FP.png', 'body.png', 'top.png', 'acce.png', 'btm.png', 'hair_s01.png', 'iraira.png')
    $original = Join-Path ([System.IO.Path]::GetTempPath()) "uka-tex-$PID"
    New-Item -ItemType Directory -Force $original | Out-Null
    $zip = [IO.Compression.ZipFile]::OpenRead($ukaArchive)
    try {
        $prefix = "uka-$ukaRevision/"
        foreach ($relative in @('MS_Uka.pmx', 'README.ja.md', 'README.md')) {
            [IO.Compression.ZipFileExtensions]::ExtractToFile($zip.GetEntry($prefix + $relative), (Join-Path $dest $relative))
        }
        foreach ($name in $ukaTextures) {
            [IO.Compression.ZipFileExtensions]::ExtractToFile($zip.GetEntry("${prefix}tex/$name"), (Join-Path $original $name))
        }
    } finally {
        $zip.Dispose()
    }
    # Downsize the 4096x4096 textures (CC BY 4.0 allows adaptation; the change is recorded below).
    $resizer = Join-Path $root "build\msvc-x64\tools\$Config\uka3d_texresize.exe"
    try {
        foreach ($name in $ukaTextures) {
            $from = Join-Path $original $name
            $to = Join-Path (Join-Path $dest 'tex') $name
            if ($UkaTextureSize -eq '4096') {
                Copy-Item -LiteralPath $from -Destination $to
            } else {
                if (-not (Test-Path -LiteralPath $resizer)) { throw "Not found: $resizer (run scripts\build.ps1 first)" }
                & $resizer $from $to $UkaTextureSize | Out-Null
                if ($LASTEXITCODE -ne 0) { throw "uka3d_texresize failed for $name" }
            }
        }
    } finally {
        Remove-Item -Recurse -Force $original
    }
    $change = if ($UkaTextureSize -eq '4096') { '改変なし（公式のファイルのまま）。' } else {
        "テクスチャ 8 枚を 4096×4096 から ${UkaTextureSize}×${UkaTextureSize} に縮小（iraira.png は元のまま）。縮小はこのプロジェクトの uka3d_texresize（sRGB を考慮し、アルファで重み付けした縮小）で行いました。モデル（MS_Uka.pmx）とその他のファイルは公式のまま。使わないテクスチャ（tex/hair.png）、PMD 版、サンプルモーションは含めていません。" }
    $credits = @"
# CG-CA Uka のクレジットと改変内容

このフォルダのモデルは、公式リポジトリの CG-CA Uka を CC BY 4.0 で利用しています。

- クレジット：CG-CA Uka (c) 2023-2024 by Nagoya Institute of Technology, Moonshot R&D Goal 1 Avatar Symbiotic Society
- 出典：https://github.com/mmdagent-ex/uka （コミット $ukaRevision）
- ライセンス：CC BY 4.0（https://creativecommons.org/licenses/by/4.0/deed.ja）
- 利用ガイドライン：README.ja.md の「利用ガイドライン」に従ってください（公式が更新することがあります）
- 改変内容：$change

ukagaka-3d-shell は公式とは関係のない、非公式のプロジェクトです。
"@
    [System.IO.File]::WriteAllText((Join-Path $dest 'CREDITS.ja.md'), $credits.Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object System.Text.UTF8Encoding($false)))
}

# Replace the generic idle / walk / sit / grab with motions fitted to the model
# (leg lengths, feet, arm angle). The walk is timed for the sample's 180 px/s
# in a 384x682 window at 96 dpi; the sample dictionary scales the speed by DPI.
$generator = Join-Path $root "build\msvc-x64\tools\$Config\uka3d_motiongen.exe"
$jsonText = [System.IO.File]::ReadAllText((Join-Path $master 'ukagaka3d.json'), [System.Text.Encoding]::UTF8)
$modelRel = [regex]::Match($jsonText, '(?m)^    "model":\s*"([^"\r\n]*)"').Groups[1].Value
$modelPath = Join-Path $master $modelRel
if (-not (Test-Path -LiteralPath $generator)) {
    Write-Warning "Motion generator not found ($generator); keeping the generic motions."
} elseif (-not (Test-Path -LiteralPath $modelPath)) {
    Write-Warning "Model not found ($modelPath); keeping the generic motions."
} else {
    $genOut = & $generator $modelPath (Join-Path $d3 'motion') --speed 180 --width 384 --height 682 --fit height 2>&1 |
        Where-Object { "$_" -match '^(rig|walk|wrote|     )' }
    $code = $LASTEXITCODE
    $genOut | ForEach-Object { Write-Host "  $_" }
    if ($code -eq 2) {
        Write-Warning 'The model has no usable leg bones; keeping the generic motions.'
    } elseif ($code -ne 0) {
        throw "uka3d_motiongen failed ($code)"
    }
}

if ($Nar) {
    $narPath = "$Output.nar"
    $zipPath = "$Output.zip"
    # Compress-Archive in Windows PowerShell 5.1 writes '\' into entry names;
    # ZIP (and therefore NAR) requires '/'. Write the entries explicitly.
    Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
    $base = (Resolve-Path -LiteralPath $Output).Path.TrimEnd('\')
    $archive = [IO.Compression.ZipFile]::Open($zipPath, [IO.Compression.ZipArchiveMode]::Create)
    try {
        foreach ($file in Get-ChildItem -LiteralPath $base -Recurse -File) {
            $entry = $file.FullName.Substring($base.Length + 1).Replace('\', '/')
            [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($archive, $file.FullName, $entry,
                [IO.Compression.CompressionLevel]::Optimal)
        }
    } finally {
        $archive.Dispose()
    }
    Move-Item -LiteralPath $zipPath -Destination $narPath
    Write-Host "NAR: $narPath"
}
Write-Host "Ghost folder: $Output" -ForegroundColor Green
Write-Host "Run: ssp.exe --ghost `"$Output`""
